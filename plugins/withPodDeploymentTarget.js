// Forces every CocoaPods target up to the app's own iOS deployment target.
//
// Why this exists: Xcode 27.1 made a stale deployment target a hard ERROR
// rather than a warning. "The iOS deployment target is set to 11.0, but the
// range of supported deployment target versions is 15.0 to 27.1.x." Several
// pods in this tree still declare 9.0, 11.0, 12.4, 13.0 or 13.4 — mostly
// resource bundles (SDWebImage, RNCAsyncStorage, RNSVGFilters, RevenueCat,
// PurchasesHybridCommon, react-native-blob-util). Xcode 26.6 tolerated them;
// 27.1 refuses to archive.
//
// The app itself is unaffected: `platform :ios` is already 15.1 and this does
// not raise it. This only drags sub-targets that are below it up to meet it,
// which is what CocoaPods would do if those podspecs were current.
//
// It lives as a plugin rather than an edit to ios/Podfile because ios/ is
// gitignored and regenerated by `expo prebuild`, so a hand edit survives
// exactly until the next prebuild and then disappears silently.
const { withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const MARKER = '# withPodDeploymentTarget';

const BLOCK = `
    ${MARKER}
    deployment_target = podfile_properties['ios.deploymentTarget'] || '15.1'
    installer.pods_project.targets.each do |target|
      target.build_configurations.each do |config|
        current = config.build_settings['IPHONEOS_DEPLOYMENT_TARGET']
        if current.nil? || Gem::Version.new(current) < Gem::Version.new(deployment_target)
          config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = deployment_target
        end
      end
    end
`;

module.exports = function withPodDeploymentTarget(config) {
  return withDangerousMod(config, ['ios', (config) => {
    const podfile = path.join(config.modRequest.platformProjectRoot, 'Podfile');
    let contents = fs.readFileSync(podfile, 'utf8');
    if (contents.includes(MARKER)) return config;
    // Append inside the existing post_install block, after react_native_post_install(...)
    contents = contents.replace(
      /(post_install do \|installer\|\n[\s\S]*?\)\n)/m,
      `$1${BLOCK}`
    );
    fs.writeFileSync(podfile, contents);
    return config;
  }]);
};
